//! TypeScript and Python types, written from the OpenAPI components.
//!
//! Both read the JSON Schema subset the model produces: references, objects
//! with properties, maps, arrays and fixed-length tuples, constants, enums,
//! unions and nullable types.

use serde_json::{Map, Value};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

const HEADER: &str = "Generated by vigo-model-gen from the vigo-model crate. Do not edit.";

fn components(openapi: &Value) -> &Map<String, Value> {
    openapi["components"]["schemas"]
        .as_object()
        .expect("components.schemas")
}

fn reference_name(schema: &Value) -> Option<&str> {
    schema.get("$ref")?.as_str()?.rsplit('/').next()
}

/// The schema's types, with `null` split out.
fn types(schema: &Value) -> (Vec<&str>, bool) {
    let listed: Vec<&str> = match schema.get("type") {
        Some(Value::String(one)) => vec![one.as_str()],
        Some(Value::Array(many)) => many.iter().filter_map(Value::as_str).collect(),
        _ => vec![],
    };
    let nullable = listed.contains(&"null");
    (
        listed.into_iter().filter(|t| *t != "null").collect(),
        nullable,
    )
}

/// A fixed-length array of one item type, such as a coordinate.
fn tuple_length(schema: &Value) -> Option<usize> {
    let (min, max) = (
        schema.get("minItems")?.as_u64()?,
        schema.get("maxItems")?.as_u64()?,
    );
    (min == max && min <= 4).then_some(min as usize)
}

fn branches(schema: &Value) -> Option<&Vec<Value>> {
    schema
        .get("oneOf")
        .or_else(|| schema.get("anyOf"))
        .and_then(Value::as_array)
}

fn literal(value: &Value) -> String {
    serde_json::to_string(value).unwrap()
}

fn comment_lines(description: Option<&str>) -> Vec<&str> {
    description.map(|d| d.lines().collect()).unwrap_or_default()
}

// ---------------------------------------------------------------- TypeScript

fn ts_type(schema: &Value) -> String {
    if schema == &Value::Bool(true)
        || schema
            .as_object()
            .is_some_and(|o| o.keys().all(|k| k == "description"))
    {
        return "unknown".into();
    }
    if let Some(name) = reference_name(schema) {
        return name.into();
    }
    if let Some(constant) = schema.get("const") {
        return literal(constant);
    }
    if let Some(Value::Array(values)) = schema.get("enum") {
        return values.iter().map(literal).collect::<Vec<_>>().join(" | ");
    }
    if let Some(branches) = branches(schema) {
        let mut parts: Vec<String> = branches.iter().map(ts_type).collect();
        parts.dedup();
        return parts.join(" | ");
    }
    let (kinds, nullable) = types(schema);
    let mut parts: Vec<String> = kinds
        .iter()
        .map(|kind| match *kind {
            "string" => "string".into(),
            "number" | "integer" => "number".into(),
            "boolean" => "boolean".into(),
            "array" if schema.get("prefixItems").is_some() => {
                let items = schema["prefixItems"].as_array().unwrap();
                format!(
                    "[{}]",
                    items.iter().map(ts_type).collect::<Vec<_>>().join(", ")
                )
            }
            "array" => {
                let item = ts_type(schema.get("items").unwrap_or(&Value::Bool(true)));
                match tuple_length(schema) {
                    Some(n) => format!("[{}]", vec![item; n].join(", ")),
                    None if item.contains(' ') => format!("Array<{item}>"),
                    None => format!("{item}[]"),
                }
            }
            "object" => ts_object(schema, ""),
            other => panic!("unsupported schema type {other}"),
        })
        .collect();
    if parts.is_empty() {
        parts.push("unknown".into());
    }
    if nullable {
        parts.push("null".into());
    }
    parts.join(" | ")
}

fn ts_key(key: &str) -> String {
    if key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !key.starts_with(|c: char| c.is_ascii_digit())
    {
        key.into()
    } else {
        literal(&Value::String(key.into()))
    }
}

fn ts_object(schema: &Value, indent: &str) -> String {
    let Some(properties) = schema.get("properties").and_then(Value::as_object) else {
        return match schema.get("additionalProperties") {
            Some(item) if item.is_object() => format!("Record<string, {}>", ts_type(item)),
            _ => "Record<string, unknown>".into(),
        };
    };
    let required: BTreeSet<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut out = String::from("{\n");
    for (key, property) in properties {
        for line in comment_lines(property.get("description").and_then(Value::as_str)) {
            writeln!(out, "{indent}  /** {line} */").unwrap();
        }
        let optional = if required.contains(key.as_str()) {
            ""
        } else {
            "?"
        };
        writeln!(
            out,
            "{indent}  {}{optional}: {};",
            ts_key(key),
            ts_type(property)
        )
        .unwrap();
    }
    out.push_str(indent);
    out.push('}');
    out
}

/// TypeScript declarations for every component schema.
pub fn typescript(openapi: &Value) -> String {
    let mut out =
        format!("// {HEADER}\n// Public VIGO requests and Results, from the OpenAPI document.\n");
    for (name, schema) in components(openapi) {
        out.push('\n');
        let lines = comment_lines(schema.get("description").and_then(Value::as_str));
        if !lines.is_empty() {
            out.push_str("/**\n");
            for line in lines {
                writeln!(out, " * {line}").unwrap();
            }
            out.push_str(" */\n");
        }
        let is_interface = schema.get("properties").is_some() && types(schema).0 == ["object"];
        if is_interface {
            writeln!(out, "export interface {name} {}", ts_object(schema, "")).unwrap();
        } else {
            writeln!(out, "export type {name} = {};", ts_type(schema)).unwrap();
        }
    }
    out
}

// -------------------------------------------------------------------- Python

fn py_type(schema: &Value) -> String {
    if schema == &Value::Bool(true)
        || schema
            .as_object()
            .is_some_and(|o| o.keys().all(|k| k == "description"))
    {
        return "Any".into();
    }
    if let Some(name) = reference_name(schema) {
        return name.into();
    }
    if let Some(constant) = schema.get("const") {
        return format!("Literal[{}]", literal(constant));
    }
    if let Some(Value::Array(values)) = schema.get("enum") {
        return format!(
            "Literal[{}]",
            values.iter().map(literal).collect::<Vec<_>>().join(", ")
        );
    }
    if let Some(branches) = branches(schema) {
        let mut parts: Vec<String> = branches.iter().map(py_type).collect();
        parts.dedup();
        return parts.join(" | ");
    }
    let (kinds, nullable) = types(schema);
    let mut parts: Vec<String> = kinds
        .iter()
        .map(|kind| match *kind {
            "string" => "str".into(),
            "integer" => "int".into(),
            "number" => "float".into(),
            "boolean" => "bool".into(),
            "array" if schema.get("prefixItems").is_some() => {
                let items = schema["prefixItems"].as_array().unwrap();
                format!(
                    "tuple[{}]",
                    items.iter().map(py_type).collect::<Vec<_>>().join(", ")
                )
            }
            "array" => {
                let item = py_type(schema.get("items").unwrap_or(&Value::Bool(true)));
                match tuple_length(schema) {
                    Some(n) => format!("tuple[{}]", vec![item; n].join(", ")),
                    None => format!("list[{item}]"),
                }
            }
            "object" => match schema.get("additionalProperties") {
                Some(item) if item.is_object() => format!("dict[str, {}]", py_type(item)),
                _ => "dict[str, Any]".into(),
            },
            other => panic!("unsupported schema type {other}"),
        })
        .collect();
    if parts.is_empty() {
        parts.push("Any".into());
    }
    if nullable {
        parts.push("None".into());
    }
    parts.join(" | ")
}

fn references(schema: &Value, into: &mut BTreeSet<String>) {
    match schema {
        Value::Object(object) => {
            if let Some(name) = reference_name(schema) {
                into.insert(name.to_owned());
            }
            object.values().for_each(|value| references(value, into));
        }
        Value::Array(items) => items.iter().for_each(|value| references(value, into)),
        _ => {}
    }
}

/// Definitions ordered so each follows the ones it uses; Python evaluates
/// TypedDict field types when they are defined.
fn dependency_order(schemas: &Map<String, Value>) -> Vec<&str> {
    let uses: BTreeMap<&str, BTreeSet<String>> = schemas
        .iter()
        .map(|(name, schema)| {
            let mut found = BTreeSet::new();
            references(schema, &mut found);
            found.remove(name);
            (name.as_str(), found)
        })
        .collect();
    let mut ordered: Vec<&str> = vec![];
    let mut placed: BTreeSet<&str> = BTreeSet::new();
    while placed.len() < uses.len() {
        let ready: Vec<&str> = uses
            .iter()
            .filter(|(name, used)| {
                !placed.contains(*name) && used.iter().all(|u| placed.contains(u.as_str()))
            })
            .map(|(name, _)| *name)
            .collect();
        assert!(
            !ready.is_empty(),
            "reference cycle among {:?}",
            uses.keys()
                .filter(|n| !placed.contains(*n))
                .collect::<Vec<_>>()
        );
        for name in ready {
            placed.insert(name);
            ordered.push(name);
        }
    }
    ordered
}

/// Python typed dictionaries and aliases for every component schema.
pub fn python(openapi: &Value) -> String {
    let schemas = components(openapi);
    let mut out = format!(
        "# {HEADER}\n\"\"\"Public VIGO requests and Results, from the OpenAPI document.\"\"\"\n\n\
         from __future__ import annotations\n\nimport sys\nfrom typing import Any, Literal\n\n\
         if sys.version_info >= (3, 11):\n    from typing import NotRequired, TypedDict\n\
         else:  # Python 3.10\n    from typing_extensions import NotRequired, TypedDict\n"
    );
    for name in dependency_order(schemas) {
        let schema = &schemas[name];
        out.push('\n');
        for line in comment_lines(schema.get("description").and_then(Value::as_str)) {
            writeln!(out, "# {line}").unwrap();
        }
        let properties = schema.get("properties").and_then(Value::as_object);
        match properties {
            Some(properties) if types(schema).0 == ["object"] => {
                let required: BTreeSet<&str> = schema
                    .get("required")
                    .and_then(Value::as_array)
                    .map(|r| r.iter().filter_map(Value::as_str).collect())
                    .unwrap_or_default();
                writeln!(
                    out,
                    "{name} = TypedDict(\n    {},\n    {{",
                    literal(&Value::String(name.into()))
                )
                .unwrap();
                for (key, property) in properties {
                    for line in comment_lines(property.get("description").and_then(Value::as_str)) {
                        writeln!(out, "        # {line}").unwrap();
                    }
                    let field = py_type(property);
                    let field = if required.contains(key.as_str()) {
                        field
                    } else {
                        format!("NotRequired[{field}]")
                    };
                    writeln!(
                        out,
                        "        {}: {field},",
                        literal(&Value::String(key.clone()))
                    )
                    .unwrap();
                }
                out.push_str("    },\n)\n");
            }
            _ => writeln!(out, "{name} = {}", py_type(schema)).unwrap(),
        }
    }
    out
}

/// Every generated file, by name.
pub fn files() -> Vec<(&'static str, String)> {
    let openapi = crate::schema::openapi();
    vec![
        (
            "openapi.json",
            serde_json::to_string_pretty(&openapi).unwrap() + "\n",
        ),
        ("vigo.ts", typescript(&openapi)),
        ("vigo_types.py", python(&openapi)),
    ]
}
