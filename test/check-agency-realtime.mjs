import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { stopBoard } from '../src/agency/stopBoard.mjs'
import { AgencyContext, serviceEpoch } from '../src/agency/agencyContext.mjs'
import { deriveOperationalState, createObservationHistory } from '../src/agency/realtimeIntelligence.mjs'
import { createAgencyFixture, observationTime, realtimeFixture, tripUpdate, sourceUrl } from './fixtures/agency.mjs'

const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'vigo-agency-'))
const file = path.join(directory, 'schedule.sqlite')
createAgencyFixture(file)
const fixtureDb = new DatabaseSync(file)
fixtureDb.exec("INSERT INTO stops VALUES('STA','River Station',42.36,-71.06,'',1,''); UPDATE stops SET parent_station='STA' WHERE stop_id='A'")
fixtureDb.close()
let context = new AgencyContext(file, 'City X')
const derive = (snapshot) => deriveOperationalState(context, snapshot, observationTime)
try {
  assert.equal(context.coverage(observationTime).valid, true)
  assert.equal(context.coverage(Date.parse('2026-10-01T12:00:00Z') / 1000).valid, false)
  assert.equal(serviceEpoch('2026-03-08', 'America/New_York'), Date.parse('2026-03-08T04:00:00Z') / 1000)
  assert.equal(serviceEpoch('2026-11-01', 'America/New_York'), Date.parse('2026-11-01T05:00:00Z') / 1000)
  const normal = derive(realtimeFixture())
  assert.equal(normal.events.length, 0)
  assert.equal(normal.routes[0].headway, 'matches-schedule')
  assert.equal(normal.routes[0].widestInterval.predictedSeconds, 600)
  assert.equal(normal.routes[0].widestInterval.scheduledSeconds, 600)
  const delayed = derive(realtimeFixture([tripUpdate('T1', 1200)]))
  assert.equal(delayed.events.find((event) => event.type === 'delay').evidence.delaySeconds, 1200)
  assert.equal(delayed.events.find((event) => event.type === 'delay').severity, 'critical')
  assert.equal(delayed.events[0].vehicleId, 'vehicle-T1')
  assert.equal(delayed.routes[0].headway, 'unknown')
  assert.equal(delayed.routes[0].widestInterval, null, 'One reporting trip cannot establish a gap')
  const laterService = derive(realtimeFixture([tripUpdate('T1', 7200)]))
  assert.equal(laterService.routes[0].maxDelaySeconds, null, 'Future departures outside the current window do not lead a live briefing')
  assert.equal(laterService.events.some((event) => event.type === 'delay'), false)
  const compressed = derive(realtimeFixture([tripUpdate('T1', 300), tripUpdate('T2')]))
  assert.equal(compressed.events.find((event) => event.type === 'bunching').evidence.headwayRatio, 0.5)
  assert.equal(compressed.events.find((event) => event.type === 'bunching').severity, 'warning')
  const overtaking = derive(realtimeFixture([tripUpdate('T1', 720), tripUpdate('T2')]))
  const reversedPair = overtaking.events.find(event => event.type === 'bunching')
  assert.equal(reversedPair?.evidence.observedHeadwaySeconds, 120, 'Overtaking must not erase a compressed scheduled pair')
  assert.equal(reversedPair.evidence.predictedOrderReversed, true)
  assert.deepEqual(reversedPair.evidence.tripIds, ['T1', 'T2'], 'Keep the scheduled pair identity when predictions cross')
  assert.equal(derive(realtimeFixture([tripUpdate('T1', 600), tripUpdate('T2')])).events.find(event => event.type === 'bunching').evidence.observedHeadwaySeconds, 0, 'Equal predicted departures remain a bunched pair')
  const cluster = derive(realtimeFixture([tripUpdate('T1', 1250), tripUpdate('T2', 700), tripUpdate('T3')]))
  assert.deepEqual(cluster.events.filter(event => event.type === 'bunching').map(event => event.evidence.observedHeadwaySeconds).sort((a, b) => a - b), [50, 100], 'Retain all members of an overtaking three-vehicle cluster')
  const reorderedWide = derive(realtimeFixture([tripUpdate('T1', 1400), tripUpdate('T2'), tripUpdate('T3')]))
  assert.equal(reorderedWide.events.some(event => event.type === 'service-gap'), false, 'A reversed pair with another prediction between it is not a next-departure gap')
  const late = realtimeFixture([tripUpdate('T1', 300), tripUpdate('T2')])
  const laterClock = observationTime + 360
  late.feeds[0].feedTimestamp = laterClock
  late.tripUpdates.forEach((update) => { update.timestamp = laterClock })
  assert.equal(deriveOperationalState(context, late, laterClock).events.find((event) => event.type === 'bunching').evidence.observedHeadwaySeconds, 300, 'Keep a late departure whose scheduled time has already passed')
  const duplicateStop = tripUpdate('T1', 300)
  duplicateStop.stopTimeUpdates.push({ ...duplicateStop.stopTimeUpdates[0], departure: { delay: 900 } })
  assert.equal(derive(realtimeFixture([duplicateStop])).events.length, 0, 'Conflicting stop predictions stay unknown')
  const wider = derive(realtimeFixture([tripUpdate('T1'), tripUpdate('T2', 600)]))
  const gap = wider.events.find((event) => event.type === 'service-gap')
  assert.equal(gap.severity, 'warning')
  assert.equal(gap.vehicleId, 'vehicle-T2')
  const severe = derive(realtimeFixture([tripUpdate('T1', -300), tripUpdate('T2', 900)]))
  assert.equal(severe.events.find(event => event.type === 'service-gap').severity, 'critical')
  assert.ok(wider.routes[0].comparedPairs > 0)
  assert.equal(gap.evidence.observedHeadwaySeconds, 1200)
  assert.equal(gap.evidence.expectedDepartures, 2)
  assert.equal(gap.evidence.reportingTrips, 2)
  assert.equal(wider.routes[0].widestInterval.predictedSeconds, 1200)
  assert.equal(wider.routes[0].widestInterval.scheduledSeconds, 600)
  assert.equal(wider.routes[0].widestInterval.stopId, gap.stopId)
  const missing = derive(realtimeFixture([tripUpdate('T1'), tripUpdate('T3', 600)]))
  assert.equal(missing.events.some((event) => event.type === 'service-gap'), false)
  assert.equal(missing.routes[0].headway, 'unknown')
  assert.equal(missing.routes[0].widestInterval, null, 'Missing intermediate trips must not inflate the displayed gap')
  assert.equal(derive(realtimeFixture([tripUpdate('T1', 1200), tripUpdate('T3')])).events.some(event => event.type === 'bunching'), false, 'Missing intermediate reports cannot establish a complete compressed pair')
  const duplicate = derive(realtimeFixture([tripUpdate('T1', 300), tripUpdate('T1', 600)]))
  assert.equal(duplicate.counts.unresolvedTrips, 2)
  assert.equal(duplicate.events.length, 0)
  assert.equal(context.matchTrip(tripUpdate('T1', 0, { directionId: 1 }), '2026-09-13').trip, undefined)
  assert.equal(context.matchTrip(tripUpdate('T1', 0, { startDate: '20260231' }), '2026-09-13').trip, undefined)
  assert.throws(() => serviceEpoch('2026-02-31', 'Etc/UTC'), /Invalid/)
  const cancelled = derive(realtimeFixture([tripUpdate('T1', 0, { scheduleRelationship: 'CANCELED' })]))
  assert.equal(cancelled.events[0].type, 'cancellation')
  const removedSnapshot = realtimeFixture([tripUpdate('T1', 0, { scheduleRelationship: 'DELETED' }), tripUpdate('T2', 0)])
  const removed = derive(removedSnapshot)
  assert.equal(removed.trips.find(trip => trip.tripId === 'T1').status, 'deleted')
  assert.equal(removed.events.some(event => event.type === 'cancellation'), false)
  const board = stopBoard(context, removedSnapshot, { stopId: 'A' }, observationTime)
  assert.equal(board.rows.some(row => row.tripId === 'T1'), false, 'Deleted service is omitted from rider boards')
  assert.equal(board.rows.some(row => row.tripId === 'T2'), true, 'Other published service remains visible')
  const skipped = derive(realtimeFixture([tripUpdate('T1', 0, { stopTimeUpdates: [{ stopId: 'B', stopSequence: 30, scheduleRelationship: 'SKIPPED' }] })]))
  assert.equal(skipped.events[0].type, 'skipped-stop')
  const terminal = derive(realtimeFixture([tripUpdate('T1', 0, { stopTimeUpdates: [{ stopId: 'C', stopSequence: 31, departure: { delay: 1200 } }] })]))
  assert.equal(terminal.events.length, 0, 'Do not invent terminal sequence 31')
  const arrivalOnly = derive(realtimeFixture([tripUpdate('T1', 0, { stopTimeUpdates: [{ stopId: 'A', arrival: { delay: 1200 } }] })]))
  assert.equal(arrivalOnly.events.length, 0)
  const stale = realtimeFixture()
  stale.feeds[0].feedTimestamp -= 181
  assert.equal(derive(stale).counts.matchedTrips, 0)
  assert.equal(derive(stale).events[0].type, 'stale-data')
  const unknown = realtimeFixture()
  delete unknown.feeds[0].feedTimestamp
  assert.equal(derive(unknown).feeds[0].status, 'unknown')
  assert.equal(derive(unknown).counts.matchedTrips, 0)
  const mixed = realtimeFixture()
  mixed.feeds.push({ sourceUrl: 'https://example.org/vehicles.pb', kind: 'vehicles', feedTimestamp: observationTime - 900 })
  assert.equal(derive(mixed).feeds[1].status, 'stale')
  assert.equal(derive(mixed).counts.matchedTrips, 3)
  const alert = realtimeFixture()
  alert.alerts.push({ id: 'alert', sourceUrl, severity: 'SEVERE', header: 'River stop closed', routeIds: ['R'], stopIds: ['A'], activePeriods: [{ start: observationTime - 60, end: observationTime + 60 }] })
  assert.equal(derive(alert).events[0].severity, 'critical')
  alert.alerts[0].stopIds = []
  context.routes.push({ ...context.routes[0], route_id: 'second\u001fR' })
  const ambiguousAlert = derive(alert).events.find((event) => event.type === 'service-alert')
  assert.deepEqual(ambiguousAlert.routeIds, [])
  alert.alerts[0].sourceScope = 'second'
  assert.deepEqual(derive(alert).events.find((event) => event.type === 'service-alert').routeIds, ['second\u001fR'])
  delete alert.alerts[0].sourceScope
  context.routes.pop()
  alert.alerts[0].activePeriods[0].end = observationTime
  assert.equal(derive(alert).counts.alerts, 0)
  assert.equal(context.resolve({ query: 'River', kind: 'stop' }).matches[0].id, 'STA', 'Use the declared parent station for place names')
  assert.equal(context.resolve({ query: 'A', kind: 'stop' }).matches[0].id, 'A', 'An explicit platform ID retains its identity')
  const history = createObservationHistory()
  assert.equal(history.update(delayed).tripHistory['T1/2026-09-13'].length, 1)
  assert.equal(history.update(delayed).tripHistory['T1/2026-09-13'].length, 1)
  const differentDay = { ...delayed, observedAt: new Date((observationTime + 1) * 1000).toISOString(), trips: delayed.trips.map(trip => ({ ...trip, serviceDate: '2026-09-14', delaySeconds: 60 })) }
  const separated = history.update(differentDay).tripHistory
  assert.equal(separated['T1/2026-09-13'][0].delaySeconds, 1200)
  assert.equal(separated['T1/2026-09-14'][0].delaySeconds, 60, 'Repeated trip IDs on different service days must not share a history series')
  context.close()
  const db = new DatabaseSync(file)
  db.exec(`INSERT INTO trips VALUES ('reverse','R','S','1'),('other-route','Q','S','0'),('inactive','R','OFF','0'),('no-direction','R','S',NULL);
    INSERT INTO connections SELECT 44100,44300,trip_id,route_id,service_id,direction_id,'A','B',10 FROM trips WHERE trip_id IN ('reverse','other-route','inactive','no-direction')`)
  context = new AgencyContext(file, 'City X')
  assert.deepEqual(context.expectedDepartures(context.tripById.get('T1'), 'A', '2026-09-13', 43500, 44700).map(row => row.trip_id), ['T1', 'T2', 'T3'], 'Shared stops retain exact route, direction, active service and inclusive time bounds')
  assert.deepEqual(context.expectedDepartures(context.tripById.get('no-direction'), 'A', '2026-09-13', 44100, 44100).map(row => row.trip_id), ['no-direction'], 'An unspecified direction stays distinct from direction zero')
  context.close()
  db.exec("INSERT INTO calendar_dates VALUES('S',20260913,2)")
  db.close()
  context = new AgencyContext(file, 'City X')
  assert.equal(context.coverage(observationTime).valid, true, 'A covered date without service is not an invalid timetable')
  assert.equal(context.coverage(observationTime).sources[0].status, 'no_service_today')
  assert.equal(context.activeServices('2026-09-13').size, 0, 'Calendar removals still override regular service')
  assert.equal(derive(realtimeFixture()).counts.matchedTrips, 0)
  context.close()
  const coverageDb = new DatabaseSync(file)
  coverageDb.exec(`DELETE FROM calendar_dates; DELETE FROM trips WHERE route_id='Q'; DELETE FROM connections WHERE route_id='Q';
    INSERT INTO routes VALUES('weekday\u001fR','W','Weekday service',3,'336699');
    INSERT INTO trips VALUES('weekday\u001fT','weekday\u001fR','weekday\u001fS',0);
    INSERT INTO calendar VALUES('weekday\u001fS',1,1,1,1,1,0,0,20260901,20260930);`)
  coverageDb.close()
  context = new AgencyContext(file, 'City X')
  assert.equal(context.coverage(observationTime).valid, true)
  assert.equal(context.coverage(observationTime).sources.find(row => row.scope === 'weekday').status, 'no_service_today')
  assert.equal(derive(realtimeFixture()).counts.matchedTrips, 3, 'An inactive Sunday feed does not block another source')
  context.close()
  const overnightDb = new DatabaseSync(file)
  overnightDb.exec(`UPDATE calendar SET end_date=20260913;
    INSERT INTO trips VALUES('LATE','R','S',0);
    INSERT INTO connections VALUES(89400,90600,'LATE','R','S',0,'A','B',10);`)
  overnightDb.close()
  context = new AgencyContext(file, 'City X')
  const overnight = Date.parse('2026-09-14T01:00:00Z') / 1000
  assert.equal(context.coverage(overnight).valid, true, 'A prior-day trip remains covered past the last calendar date')
  assert.equal(context.coverage(overnight).sources.find(row => row.scope === '').status, 'continuing_service')
  assert.equal(context.matchTripIdentity({ tripId: 'LATE', startDate: '20260913' }, '2026-09-14').trip.trip_id, 'LATE')
  assert.equal(context.coverage(overnight + 3600).valid, false, 'Coverage ends when the indexed spillover service ends')
  console.log('Agency realtime: schedule dates, DST, exact stops, delay, headways, missing reports, cancellation, skipped stops, independent freshness, alerts, history passed.')
} finally {
  context.close()
  await fs.rm(directory, { recursive: true, force: true })
}
