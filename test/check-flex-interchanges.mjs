import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import JSZip from 'jszip'
import { writeCliFixtureInputs } from './helpers/cli-fixture-inputs.mjs'
import { standaloneBinary } from './helpers/standalone-runtime.mjs'
const folder = fs.mkdtempSync(path.join(os.tmpdir(),'vigo-flex-interchanges-'))
try {
  const {gtfsPath,osmPath} = await writeCliFixtureInputs(folder,{wheelchair:true})
  const zip = await JSZip.loadAsync(fs.readFileSync(gtfsPath))
  zip.file('stops.txt','stop_id,stop_name,stop_lat,stop_lon,wheelchair_boarding\nA,Alpha,38.900,-77.050,1\nX,Transfer,38.905,-77.040,1\nB,Bravo,38.910,-77.030,1\n')
  zip.file('trips.txt','route_id,service_id,trip_id,direction_id,wheelchair_accessible\nR1,WKD,F,0,1\nR2,WKD,T2,0,1\n')
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,pickup_type,drop_off_type\nF,08:00:00,08:00:00,A,1,2,1\nF,08:10:00,08:10:00,X,2,1,2\nT2,08:15:00,08:15:00,X,1,0,1\nT2,08:30:00,08:30:00,B,2,1,0\n')
  let count=0
  const build=async (wheelchair=false)=>{
    fs.writeFileSync(gtfsPath,await zip.generateAsync({type:'nodebuffer'}))
    const city=path.join(folder,`city-${count++}`)
    execFileSync(process.execPath,['public/vigo.mjs','build','--gtfs',gtfsPath,'--osm',osmPath,'--output',city,...(wheelchair?['--wheelchair']:[])],{stdio:'pipe'})
    return (kind,q)=>JSON.parse(execFileSync(standaloneBinary,[kind,'--city',city,'--request','-'],{input:JSON.stringify({...q,diagnostics:'trace'}),encoding:'utf8'}))
  }
  const base={origin:{stopId:'A'},destination:{stopId:'B'},serviceDate:'2026-07-15',time:'07:59',maxWalkKm:0,requireTransitRide:true,flex:{}}
  let query=await build()
  assert.equal(query('route',{...base,flex:undefined}).status,'not_found')
  let route=query('route',base)
  assert.equal(route.journey.arrivalTime,'08:30:00')
  assert.equal(route.trace.transfers,1)
  const access=query('route',{...base,destination:{stopId:'X'}})
  const onward=query('route',{...base,flex:undefined,origin:{stopId:'X'},time:access.journey.arrivalTime})
  assert.equal(route.journey.arrivalTime,onward.journey.arrivalTime,'Composition agrees with independent native legs')
  assert.deepEqual(route.trace.legs.filter(l=>l.kind==='ride').map(l=>l.tripId),['F','T2'])
  assert.equal(query('route',{...base,maxTransfers:0}).status,'not_found')
  const reverse=query('route',{...base,time:'08:30',timePreference:'arrive_by'})
  assert.equal(reverse.journey.departureTime,'08:00:00')
  const {origin,destination,...options}=base
  const matrix=query('matrix',{...options,origins:[origin],destinations:[destination],includeJourneys:true})
  assert.equal(matrix.trace.durationsMinutes[0][0],31)
  assert.deepEqual(matrix.trace.journeys[0][0].legs,route.trace.legs)
  const scheduledTrips=await zip.file('trips.txt').async('string'), scheduledCalls=await zip.file('stop_times.txt').async('string')
  zip.file('trips.txt',scheduledTrips+'R1,WKD,T1,0,1\n')
  zip.file('stop_times.txt',scheduledCalls+'T1,08:00:00,08:00:00,A,1,0,1\nT1,08:10:00,08:10:00,X,2,1,0\n')
  const tied=await build()
  assert.deepEqual(tied('route',base).journey.legs,tied('route',{...base,flex:undefined}).journey.legs,'An equal-time conditional service must not displace the scheduled journey')
  zip.file('trips.txt',scheduledTrips); zip.file('stop_times.txt',scheduledCalls)
  const accessible=await build(true)
  assert.equal(accessible('route',{...base,wheelchair:true}).journey?.arrivalTime,'08:30:00', JSON.stringify(accessible('route',{...base,wheelchair:true})))
  zip.file('transfers.txt','from_stop_id,to_stop_id,from_trip_id,to_trip_id,transfer_type\nX,X,F,T2,3\n')
  query=await build()
  assert.equal(query('route',base).status,'not_found','Scoped forbidden Flex interchange must remain forbidden')
  zip.file('transfers.txt','from_stop_id,to_stop_id,from_trip_id,to_route_id,transfer_type,min_transfer_time\nX,X,F,R2,2,600\n')
  zip.file('trips.txt',(await zip.file('trips.txt').async('string'))+'R2,WKD,T3,0,1\n')
  zip.file('stop_times.txt',(await zip.file('stop_times.txt').async('string'))+'T3,08:25:00,08:25:00,X,1,0,1\nT3,08:40:00,08:40:00,B,2,1,0\n')
  query=await build()
  assert.equal(query('route',base).journey.arrivalTime,'08:40:00','A missed minimum must find the later feasible departure')
  zip.file('transfers.txt','from_stop_id,to_stop_id,from_trip_id,to_route_id,transfer_type\nX,X,F,R2,1\n')
  query=await build()
  assert.equal(query('route',{...base,minimumTransferBufferMinutes:10}).journey.arrivalTime,'08:30:00','Timed transfer waives the default buffer')
  zip.remove('transfers.txt')
  zip.file('trips.txt','route_id,service_id,trip_id,direction_id,wheelchair_accessible\nR1,WKD,T1,0,1\nR2,WKD,F,0,1\n')
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,pickup_type,drop_off_type\nT1,08:00:00,08:00:00,A,1,0,1\nT1,08:10:00,08:10:00,X,2,1,0\nF,08:15:00,08:15:00,X,1,2,1\nF,08:30:00,08:30:00,B,2,1,2\n')
  query=await build()
  assert.deepEqual(query('route',base).trace.legs.filter(l=>l.kind==='ride').map(l=>l.tripId),['T1','F'])
  assert.equal(query('route',{...base,time:'08:30',timePreference:'arrive_by'}).journey.departureTime,'08:00:00')
  zip.file('trips.txt','route_id,service_id,trip_id,direction_id,shape_id,wheelchair_accessible\nR1,WKD,C,0,S,1\n')
  zip.file('routes.txt','route_id,route_short_name,route_type,continuous_pickup,continuous_drop_off\nR1,C,3,0,0\n')
  zip.file('shapes.txt','shape_id,shape_pt_lat,shape_pt_lon,shape_pt_sequence,shape_dist_traveled\nS,38.9,-77.05,1,0\nS,38.905,-77.04,2,1\nS,38.91,-77.03,3,2\n')
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,shape_dist_traveled\nC,08:00:00,08:00:00,A,1,0\nC,08:20:00,08:20:00,B,2,2\n')
  query=await build()
  const continuous={...base,origin:{coordinate:[-77.04,38.905]},maxWalkKm:0.001}
  route=query('route',continuous)
  assert.equal(route.journey.arrivalTime,'08:20:00')
  assert(Math.abs(route.trace.departureMinutes-490)<0.001)
  assert.equal(route.journey.legs.find(l=>l.kind==='ride'||l.mode==='transit')?.quality?.flex?.assumption ?? route.trace.legs.find(l=>l.kind==='ride').flexEstimate.assumption,'interpolated_shape')
  assert.equal(query('route',{...continuous,origin:base.destination,destination:continuous.origin}).status,'not_found')
  const accessibleContinuous=await build(true)
  assert.equal(accessibleContinuous('route',{...continuous,wheelchair:true}).journey.arrivalTime,'08:20:00')
  const publishedShape=await zip.file('shapes.txt').async('string')
  zip.file('shapes.txt',publishedShape.replace('S,38.905,-77.04,2,1','S,38.905,-77.055,2,1'))
  const inaccessibleRoadside=await build(true)
  assert.equal(inaccessibleRoadside('route',{...continuous,wheelchair:true,origin:{coordinate:[-77.055,38.905]}}).status,'not_found','A zero-length roadside access still requires strict street evidence')
  zip.file('shapes.txt',publishedShape)
  zip.file('trips.txt',(await zip.file('trips.txt').async('string')).replace('C,0,S,1','C,0,S,0'))
  const unknown=await build(true)
  assert.equal(unknown('route',{...continuous,wheelchair:true}).status,'not_found','Unknown vehicle accessibility cannot be used')
  zip.file('trips.txt',(await zip.file('trips.txt').async('string')).replace('C,0,S,0','C,0,S,1'))
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,shape_dist_traveled,continuous_pickup,continuous_drop_off\nC,08:00:00,08:00:00,A,1,0,1,1\nC,08:20:00,08:20:00,B,2,2,1,1\n')
  const noContinuous=await build()
  assert.equal(noContinuous('route',continuous).status,'not_found','Stop-time restrictions override route continuous permissions')
  zip.file('routes.txt','route_id,route_short_name,route_type,continuous_pickup,continuous_drop_off\nR1,C,3,3,2\n')
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,shape_dist_traveled\nC,08:00:00,08:00:00,A,1,0\nC,08:20:00,08:20:00,B,2,2\n')
  query=await build()
  const coordinated=query('route',{...continuous,destination:{coordinate:[-77.035,38.9075]}})
  const estimate=coordinated.trace.legs.find(l=>l.kind==='ride').flexEstimate
  assert.equal(estimate.driverCoordination,true)
  assert.equal(estimate.bookingStatus,'required')
  zip.file('routes.txt','route_id,route_short_name,route_type\nR1,F,3\nR2,T,3\n')
  zip.file('trips.txt','route_id,service_id,trip_id,wheelchair_accessible\nR1,WKD,F,1\nR2,WKD,T2,1\n')
  zip.file('stop_times.txt','trip_id,arrival_time,departure_time,stop_id,stop_sequence,location_id,start_pickup_drop_off_window,end_pickup_drop_off_window,pickup_type,drop_off_type\nF,,,,1,Z,08:00:00,09:00:00,2,1\nF,,,X,2,,08:00:00,09:00:00,1,2\nT2,08:15:00,08:15:00,X,1,,,,0,1\nT2,08:30:00,08:30:00,B,2,,,,1,0\n')
  zip.file('locations.geojson',JSON.stringify({type:'FeatureCollection',features:[{type:'Feature',id:'Z',geometry:{type:'Polygon',coordinates:[[[-77.06,38.89],[-77.045,38.89],[-77.045,38.903],[-77.06,38.903],[-77.06,38.89]]]}}]}))
  const wheelchairZone=await build(true)
  assert.equal(wheelchairZone('route',{...base,wheelchair:true}).journey.arrivalTime,'08:30:00','Wheelchair zone service connects to accessible transit')
  assert.equal(wheelchairZone('route',{...base,wheelchair:true,origin:{coordinate:[-77.0500001,38.9]}}).status,'not_found','Zero walking does not allow a real road attachment gap')
  assert.throws(()=>wheelchairZone('route',{...base,flex:undefined,wheelchair:true,mode:'drive'}),/supports transit and walk/)
  console.log('Flex interchange directions, reverse clocks, scoped restrictions, Matrix parity, wheelchair and directed continuous pickup passed.')
} finally { fs.rmSync(folder,{ recursive: true, force: true, maxRetries: 20, retryDelay: 50 }) }
